"""Kindle library book TEXT — DRM-stripped EPUB/TXT from MinIO → kindle/raw/books/ (B165 — Kindle-library RAG).

The extraction VM (docs/runbooks/kindle-rag.md) strips DRM and uploads EPUB/TXT to the plain MinIO bucket
`kindle-corpus`; this lander reads each book, extracts readable text + chapter structure with the dagster-free
`kindle_text_parse` helper, and chunks it chapter-aware into one tidy raw table:

  - books  (book_id, title, author, section, chunk_id, text)

Mirrors the finance filings-text lander (B113 Phase 3): the land scaffold — freshness skip, fail-closed on zero
rows, the lakeFS write, row-count metadata — is generated by `datasets_lib.landers.build_land_asset`; this file
carries only the MinIO read + text extraction + the `_produce` that shapes the one table. The SOURCE read is
plain MinIO (the same `MINIO_*` env the B37 aidlc_kb ingest uses); the land WRITE goes through the lakeFS gateway
(the factory's `io.client()`), so a book's raw chunks are versioned like every other mesh dataset.
"""
import os

import pyarrow as pa

from .datasets_lib.kindle_text_parse import extract_and_chunk
from .datasets_lib.landers import build_land_asset

_SOURCE_EXTS = (".epub", ".txt")


def _read_source_books(context):
    """Pull every EPUB/TXT out of the `kindle-corpus` MinIO bucket → chunk rows. Plain MinIO (not lakeFS): the
    VM uploaded the DRM-stripped files here. Returns (all_rows, per_book_chunk_counts)."""
    from minio import Minio

    endpoint = os.environ.get("MINIO_ENDPOINT", "minio.minio.svc.cluster.local:9000")
    bucket = os.environ.get("KINDLE_SOURCE_BUCKET", "kindle-corpus")
    secure = os.environ.get("MINIO_SECURE", "false").lower() == "true"
    client = Minio(endpoint, access_key=os.environ["MINIO_ACCESS_KEY"],
                   secret_key=os.environ["MINIO_SECRET_KEY"], secure=secure)

    all_rows, per_book = [], {}
    seen = set()  # a book exported as BOTH .epub and .txt would double-count — keep the first (epub sorts first)
    for obj in sorted(client.list_objects(bucket, recursive=True), key=lambda o: o.object_name):
        key = obj.object_name
        if not key.lower().endswith(_SOURCE_EXTS):
            continue
        stem = key.rsplit("/", 1)[-1].rsplit(".", 1)[0]
        if stem in seen:
            context.log.info(f"kindle: skip {key} — already ingested book_id '{stem}'")
            continue
        resp = client.get_object(bucket, key)
        try:
            data = resp.read()
        finally:
            resp.close()
            resp.release_conn()
        try:
            rows = extract_and_chunk(key, data)
        except Exception as e:  # noqa: BLE001 — one unreadable book must not sink the whole land
            per_book[stem] = f"ERROR: {e}"
            context.log.warning(f"kindle: {key}: {e}")
            continue
        if not rows:
            per_book[stem] = 0  # a book with no extractable text (valid outcome — reported, not fatal)
            context.log.warning(f"kindle: {key}: 0 chunks (no extractable text?)")
            continue
        seen.add(stem)
        all_rows.extend(rows)
        per_book[stem] = len(rows)
        context.log.info(f"kindle: {key}: {len(rows)} chunks")
    return all_rows, per_book


def _build_books_table(rows):
    """Tidy chunk rows → the fixed books silver schema (the vector fan-out reads the ``text`` column)."""
    def col(k):
        return [r[k] for r in rows]
    return pa.table({
        "book_id": pa.array(col("book_id"), type=pa.string()),
        "title": pa.array(col("title"), type=pa.string()),
        "author": pa.array(col("author"), type=pa.string()),
        "section": pa.array(col("section"), type=pa.string()),
        "chunk_id": pa.array(col("chunk_id"), type=pa.int64()),
        "text": pa.array(col("text"), type=pa.string()),
    })


def _produce(context):
    """Read + chapter-chunk every book in `kindle-corpus` → the one text table + a per-book chunk-count detail.
    An empty bucket (nothing extracted yet) leaves ``tables`` empty → the factory fails closed rather than
    committing an empty raw layer that would read downstream as a successful-but-empty catalog."""
    all_rows, per_book = _read_source_books(context)
    context.log.info(f"kindle: {len(per_book)} book(s), {len(all_rows)} chunks total")
    tables = {"books": _build_books_table(all_rows)} if all_rows else {}
    return tables, per_book


datasets_kindle_books_land = build_land_asset(
    "datasets_kindle_books_land", "kindle", _produce,
    group="datasets_kindle",
    description="Land DRM-stripped EPUB/TXT book text (chapter-aware chunks) from MinIO kindle-corpus → kindle/raw/books/.",
)
